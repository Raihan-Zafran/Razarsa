class L {
  static String lang = 'id'; // 'id' | 'en'
  static String currency = 'IDR'; // 'IDR' | 'USD'

  static bool get en => lang == 'en';
  static String get dateLocale => en ? 'en_US' : 'id_ID';
}

/// Untuk tes: apakah teks ini punya terjemahan Inggris.
bool hasEnglish(String id) => _en.containsKey(id);

/// Terjemahkan teks Indonesia ke bahasa aktif.
String tr(String id) => L.en ? (_en[id] ?? id) : id;

/// Terjemahan dengan isian: trf('Sisa {0}', [rp(x)]).
String trf(String id, List<Object?> args) {
  var s = tr(id);
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

